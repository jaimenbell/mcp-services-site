"""Tests for scripts/check_beacon_coverage.py.

Uses only temp fixtures (tmp_path) -- never touches the real site content files
(index.html, case-studies/*.html, scripts/generate-scoreboard.mjs), per the
lane contract's rule that tests must not mutate real site files.

Enforces docs/INSTRUMENTATION-SETUP.md's "Coverage rule" (lines 38-64): every
user-facing *.html page carries EXACTLY ONE data-goatcounter tag. Zero fails
(missing beacon). Two fails (duplicate beacon, double-counts views). The
producer/consumer parity case (scoreboard.html vs its generator template) is
the one a naive scan-the-output-only check gets wrong -- see
test_generator_template_losing_beacon_fails_even_when_output_still_has_one.
"""

import shutil
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "scripts"))

import check_beacon_coverage as cbc  # noqa: E402

BEACON_TAG = (
    '<script data-goatcounter="https://jaimenbell.goatcounter.com/count" '
    'async src="//gc.zgo.at/count.js"></script>'
)


def write(tmp_path: Path, name: str, content: str) -> Path:
    p = tmp_path / name
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(content, encoding="utf-8")
    return p


