def test_known_good_tree_mirroring_real_26_of_26_state_stays_silent(tmp_path):
    """A tree shaped like the real repo's current coverage state (every
    user-facing page carrying exactly one tag, generator template carrying
    exactly one tag too) must pass clean -- a check that cannot stay silent
    on good input is as broken as one that cannot fire on bad input."""
    site = tmp_path / "site"
    pages = [
        "index.html", "404.html", "managed-watch.html", "scoreboard.html",
        "articles/build-custom-mcp-server.html",
        "case-studies/mcp-factory.html",
        "case-studies/mcp-security-scanner.html",
    ]
    for p in pages:
        write(site, p, f"<html><head>{BEACON_TAG}</head><body>content</body></html>\n")
    write(
        site, "scripts/generate-scoreboard.mjs",
        f"const html = `<head>{BEACON_TAG}</head>`;\n",
    )

    exit_code = cbc.run(
        root=site,
        target_patterns=["404.html", "index.html", "managed-watch.html",
                          "scoreboard.html", "articles/*.html", "case-studies/*.html"],
        generated_pairs={"scoreboard.html": "scripts/generate-scoreboard.mjs"},
    )

    assert exit_code == 0


