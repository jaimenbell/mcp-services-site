def test_resolve_targets_only_matches_explicit_globs_not_implicit_walk(tmp_path):
    """Population is an explicit glob list (imitating check_proof_numbers.py's
    DEFAULT_TARGET_GLOBS idiom), never an implicit directory walk -- a page
    dropped somewhere the globs don't name is simply out of scope, not
    silently swept in. Here scripts/og-card.html and a nested throwaway
    worktree copy are both present on disk but excluded by the glob list."""
    site = tmp_path / "site"
    write(site, "index.html", "a")
    write(site, "scripts/og-card.html", "b")
    write(site, ".claude/worktrees/foo/index.html", "c")

    targets = cbc.resolve_targets(site, ["index.html"])

    assert [t.name for t in targets] == ["index.html"]
    assert all(".claude" not in str(t) for t in targets)
    assert all("og-card" not in str(t) for t in targets)


