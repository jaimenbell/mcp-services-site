def test_main_crash_path_reports_nonzero_not_a_verdict_code(tmp_path, monkeypatch):
    """An unhandled exception inside the gate itself (a fault, not a verdict)
    must exit non-zero but distinct from the checker's own verdict path --
    exercised here by pointing at a root that does not exist, which raises
    rather than quietly resolving to zero targets in a broken state."""
    def _boom(*a, **kw):
        raise RuntimeError("simulated gate fault")

    monkeypatch.setattr(cbc, "resolve_targets", _boom)
    exit_code = cbc.main([])
    assert exit_code not in (0, 2)


