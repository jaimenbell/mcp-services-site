@pytest.mark.parametrize("page", in_scope_pages(), ids=lambda p: p.name)
def test_inline_svgs_are_accessible_and_themed(page: Path) -> None:
    source = page.read_text(encoding="utf-8")
    problems = check_svg_source(source) + check_figure_copy(source)
    assert not problems, f"{page.relative_to(REPO_ROOT)}:\n  " + "\n  ".join(problems)


def test_scope_is_non_empty() -> None:
    """A guard that matches nothing is satisfied by silence.

    If the globs ever stop resolving, this fails loudly instead of the
    suite going quietly green on zero pages.
    """
    pages = in_scope_pages()
    assert len(pages) >= 20, f"expected the article/case-study corpus, got {len(pages)}"


# --------------------------------------------------------------------------
# Positive controls -- the checker must FIRE on known-bad and STAY SILENT
# on known-good. A check never shown to fire is not a check.
# --------------------------------------------------------------------------

GOOD = """
<figure class="diagram">
  <svg role="img" aria-labelledby="d1t" viewBox="0 0 100 40">
    <title id="d1t">A one-line description of the mechanism.</title>
    <rect x="1" y="1" width="20" height="10" fill="var(--card)"
          stroke="var(--muted)"/>
    <text x="4" y="9" fill="var(--text)">ok</text>
  </svg>
  <figcaption>A caption that stands on its own.</figcaption>
</figure>
"""

GOOD_DECORATIVE = """
<svg aria-hidden="true" viewBox="0 0 10 10">
  <circle cx="5" cy="5" r="4" fill="var(--border)"/>
</svg>
"""

BAD_CASES = {
    "no_role": GOOD.replace('role="img" ', ""),
    "no_title": GOOD.replace('<title id="d1t">A one-line description of the mechanism.</title>', ""),
    "empty_title": GOOD.replace("A one-line description of the mechanism.", "   "),
    "no_labelledby": GOOD.replace('aria-labelledby="d1t" ', ""),
    "dangling_labelledby": GOOD.replace('aria-labelledby="d1t"', 'aria-labelledby="nope"'),
    "no_figure": GOOD.replace("<figure class=\"diagram\">", "").replace("</figure>", ""),
    "no_figcaption": GOOD.replace(
        "<figcaption>A caption that stands on its own.</figcaption>", ""
    ),
    "empty_figcaption": GOOD.replace("A caption that stands on its own.", "  "),
    "no_viewbox": GOOD.replace('viewBox="0 0 100 40"', ""),
    "fixed_width": GOOD.replace('viewBox="0 0 100 40"', 'viewBox="0 0 100 40" width="900"'),
    "fixed_height": GOOD.replace('viewBox="0 0 100 40"', 'viewBox="0 0 100 40" height="480"'),
    "hardcoded_hex": GOOD.replace('fill="var(--text)"', 'fill="#e8edf6"'),
    "em_dash_in_title": GOOD.replace("mechanism.", "mechanism — really."),
    # Non-hex hardcoded colors: a hex-only guard would wave these through.
    "named_color_fill": GOOD.replace('fill="var(--text)"', 'fill="white"'),
    "named_color_stroke": GOOD.replace('stroke="var(--muted)"', 'stroke="black"'),
    "rgb_function": GOOD.replace('fill="var(--text)"', 'fill="rgb(231,236,243)"'),
    "hsl_function": GOOD.replace('fill="var(--card)"', 'fill="hsl(220 30% 12%)"'),
    # The em-dash lives only in the caption, outside the <svg> block.
    "em_dash_in_figcaption_only": GOOD.replace(
        "A caption that stands on its own.", "A caption — with an em-dash."
    ),
}


def test_positive_control_good_markup_is_silent() -> None:
    assert check_svg_source(GOOD) == []
    assert check_figure_copy(GOOD) == []


def test_positive_control_decorative_svg_is_exempt_from_labelling() -> None:
    """The aria-hidden carve-out is real: no role/title/figure demanded..."""
    assert check_svg_source(GOOD_DECORATIVE) == []


def test_positive_control_decorative_svg_still_guarded_on_the_rest() -> None:
    """...but a decorative diagram is NOT exempt from viewBox/hex/em-dash."""
    bad = GOOD_DECORATIVE.replace('viewBox="0 0 10 10"', 'width="800"')
    problems = check_svg_source(bad)
    assert any("viewBox" in p for p in problems), problems
    assert any("fixed width" in p for p in problems), problems

    hexed = GOOD_DECORATIVE.replace('fill="var(--border)"', 'fill="#233048"')
    assert any("hardcoded color" in p for p in check_svg_source(hexed))


@pytest.mark.parametrize("name", sorted(BAD_CASES))
def test_positive_control_bad_markup_fires(name: str) -> None:
    source = BAD_CASES[name]
    problems = check_svg_source(source) + check_figure_copy(source)
    assert problems, f"checker stayed silent on known-bad case {name!r}"


def test_positive_control_second_figures_caption_cannot_rescue_the_first() -> None:
    """A later figure's caption must not be credited to an earlier svg.

    The parser assigns captions per figure. If it instead assigned the
    first empty caption it could find, this two-figure page would pass
    with figure #1 uncaptioned. That is a false negative, so it gets its
    own control rather than relying on the single-figure cases.
    """
    empty_first = GOOD.replace("A caption that stands on its own.", "  ")
    two = empty_first + GOOD
    problems = check_svg_source(two)
    assert any("no <figcaption> text" in p for p in problems), problems
    # ...and the well-formed second figure must not be blamed for it.
    assert sum("no <figcaption> text" in p for p in problems) == 1, problems


def test_positive_control_two_good_figures_stay_silent() -> None:
    assert check_svg_source(GOOD + GOOD) == []


def test_positive_control_unreferenced_title_cannot_supply_the_name() -> None:
    """An empty REFERENCED title is not rescued by a populated sibling.

    The accessible name comes from the node aria-labelledby points at. A
    guard that only asked "is some <title> non-empty" would pass this SVG
    while a screen reader announced nothing.
    """
    two_titles = GOOD.replace(
        '<title id="d1t">A one-line description of the mechanism.</title>',
        '<title id="d1t"></title>'
        '<title id="other">Text on a title nobody references.</title>',
    )
    problems = check_svg_source(two_titles)
    assert any("accessible name is blank" in p for p in problems), problems


def test_positive_control_em_dash_in_caption_only_is_caught() -> None:
    src = BAD_CASES["em_dash_in_figcaption_only"]
    # Clean inside the <svg>...
    assert not any("em-dash" in p for p in check_svg_source(src))
    # ...and still caught at the figure level.
    assert any("em-dash" in p for p in check_figure_copy(src))


def test_indeterminate_on_nested_svg_rather_than_a_finding() -> None:
    """A check that cannot discriminate must say so, not emit a verdict."""
    nested = """
    <figure><svg role="img" aria-labelledby="a" viewBox="0 0 10 10">
      <title id="a">outer</title><svg viewBox="0 0 5 5"></svg>
    </svg><figcaption>c</figcaption></figure>
    """
    problems = check_svg_source(nested)
    assert len(problems) == 1
    assert problems[0].startswith("INDETERMINATE")
